import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Writes skills/context7-mcp/SKILL.md into src/lib/skill-md.ts, which src/lib/skills.ts serves.
 * Committed, so the npm package, the Docker image and the mcpb bundle carry the skill without
 * copying files at build time. Run `pnpm build:skill` after changing SKILL.md; CI fails when
 * the module is out of date.
 */
const root = dirname(fileURLToPath(import.meta.url));
const skill = readFileSync(resolve(root, "../../../skills/context7-mcp/SKILL.md"), "utf8");
writeFileSync(
  resolve(root, "../src/lib/skill-md.ts"),
  "// Generated by `pnpm build:skill` from skills/context7-mcp/SKILL.md. Do not edit by hand.\n" +
    `export const CONTEXT7_MCP_SKILL = ${JSON.stringify(skill)};\n`
);
