import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { defineConfig, type Plugin } from "vite";
import { viteSingleFile } from "vite-plugin-singlefile";

const root = dirname(fileURLToPath(import.meta.url));

/**
 * Writes the built page into src/ui/console-html.ts, which the server imports.
 * Committed: Vercel compiles api/ and src/ and runs no UI build, so the server
 * has to find the page as source. Run `pnpm build:ui` after changing ui/.
 */
function emitServerModule(): Plugin {
  return {
    name: "emit-server-module",
    apply: "build",
    enforce: "post",
    // After the single-file plugin has inlined every script and stylesheet.
    writeBundle(options) {
      const html = readFileSync(resolve(options.dir!, "console.html"), "utf8");
      const target = resolve(root, "../src/ui/console-html.ts");
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(
        target,
        "// Generated by `pnpm build:ui` from ui/. Do not edit by hand.\n" +
          "// The Context7 console MCP App page, served at ui://context7/console (src/console.ts).\n" +
          `export const CONSOLE_HTML = ${JSON.stringify(html)};\n`
      );
    },
  };
}

export default defineConfig({
  root,
  plugins: [react(), tailwindcss(), viteSingleFile(), emitServerModule()],
  build: {
    outDir: resolve(root, "dist"),
    emptyOutDir: true,
    rollupOptions: { input: resolve(root, "console.html") },
  },
});
